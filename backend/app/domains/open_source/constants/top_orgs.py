def _build_boundary_pattern(tokens: list[str]) -> str:
    """词元边界正则：命中前后为非字母数字（或字符串边界），大小写不敏感由 ~* 保证。"""
    alt = "|".join(re.escape(t) for t in tokens)
    return rf"(^|[^a-zA-Z0-9])({alt})([^a-zA-Z0-9]|$)"


TOP_ORG_RE = _build_boundary_pattern(TOP_ORG_TOKENS)
